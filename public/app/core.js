// Shared runtime: graph lookups, walk/focus/level, review marks, settings. Views only talk to this.
export const BANDS = ["upUnchanged", "upChanged", "core", "downChanged", "downUnchanged"];
export const BAND_TEXT = {
  upUnchanged: "Relies on · untouched",
  upChanged: "Relies on · changed",
  core: "Core change",
  downChanged: "Affects · changed",
  downUnchanged: "Affects · untouched",
};
export const LEVELS = ["Overview", "Core", "Page"];
export const LOW = "@low"; // pseudo-placement: low-signal hunks
export const DONE = "@done"; // pseudo-placement: end of walk

export const DEFAULT_SETTINGS = {
  view: "diff", // the first view; after that, the one you used last
  updates: "on", // on | off: check GitHub for a newer Bobby (updates.ts)
  theme: "system", // system | dark | light
  font: "sans", // sans | hyper | serif | mono
  size: 15,
  spacing: "normal", // normal | wide | wider
  motion: "system", // system | on | off
  hints: "fade", // fade | always | never
  timebox: 0, // minutes; 0 = off
  edges: "all", // all | focus: Diff draws background edges, or only the focused ones
  rabbit: 12, // minutes on one page before offering to flag it and move on; 0 = off
  drift: "on", // on | off: after 90s idle on a page, offer to park a thought
  comments: "open", // open | collapsed: comments and notes in place, open or as a slim marker (per file and thread too)
  untouched: "hide", // hide | show: untouched code the changes rely on or affect, in every view (the top bar's switch)
  tests: "hide", // hide | show: test files and generated files, in every view (the top bar's switch)
  fileTree: "show", // show | hide: the file tree beside the view (t)
  fileTreeSide: "right", // right | left
  diffLayout: "split", // split | inline: old beside new, or changed lines in one column
  palette: "github", // github | warm | silverpoint: colours (and, for github, fonts); theme picks dark or light
  hintUses: {},
  tour: "unseen", // unseen | seen: the first-run tour is offered once
  news: [], // ids of the what's-new notes already seen
};

/** Whether an element is on screen in the current view: laid out, and not in the Diff view kept parked while you're in
 *  another (content-visibility: hidden keeps its layout, so offsetParent alone says yes). */
export const live = (el) => !!el?.offsetParent && !el.closest(".parked");
export const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
/** Escaped text with `backtick` spans as <code>, for model-written prose like hooks. */
export const inline = (s) => esc(s).replace(/`([^`]+)`/g, "<code>$1</code>");
/** A call to Bobby's server. Rejects when it fails: the server can't be reached (stopped, or the laptop slept), or it
 *  answers an error. An answer that carries its own ok: false (submit) is the caller's to read. */
/** This page's review, as the app addresses it: /r/<id>; its API is under it. */
export const reviewBase = location.pathname.startsWith("/r/") ? location.pathname.replace(/\/+$/, "") : "";
export async function api(url, body, method = body ? "POST" : "GET") {
  if (url.startsWith("/api/") && url !== "/api/avatar" && !url.startsWith("/api/avatar?")) url = reviewBase + url;
  let r;
  try { r = await fetch(url, { method, headers: body ? { "content-type": "application/json" } : {}, body: body ? JSON.stringify(body) : undefined }); }
  catch { throw new Error("Bobby isn't answering. Is it still running in your terminal?"); }
  const j = await r.json().catch(() => ({}));
  if (!r.ok && !("ok" in j)) throw new Error(j.error ?? `${r.status} ${r.statusText}`);
  return j;
}

// Some placements can be switched off: untouched code a change relies on or affects (settings.untouched), and test or generated
// files (settings.tests). Switched off, they leave the walk, the edges and every view, as if the graph never had them.
const TEST_PATH = /(^|\/)(__tests__|__mocks__|tests?|specs?|e2e|fixtures?|testdata|test-?utils?)\/|[._-](test|spec|e2e)\.[a-z0-9]+$|(^|\/)test_[^/]+\.py$|_test\.(go|py|rb|exs?)$/i;
const GENERATED_PATH = /(^|\/)(__generated__|generated|gen)\/|\.(generated|gen|g|pb)\.[a-z0-9]+$|_pb2(_grpc)?\.py$|(^|\/)openapi[^/]*\.(json|ya?ml)$/i;
const GENERATED_MARK = /@generated\b|\bDO NOT EDIT\b|\bcode generated by\b|\bauto-?generated\b|\bautomatically generated\b|^\s*(\/\/|#|\/\*+|\*)\s*generated by\b/i;
/** A node is test or generated code: by its path, or by a generated-file marker in the code shown. */
export function isTestOrGenerated(node, ix) {
  if (!node) return false;
  const path = node.kind === "change" ? node.file : node.location?.path ?? "";
  if (TEST_PATH.test(path) || GENERATED_PATH.test(path)) return true;
  const lines = node.kind === "change" ? (node.hunkIds ?? []).flatMap((h) => ix.hunk.get(h)?.lines.map((l) => l.s) ?? []) : node.snippet?.lines ?? [];
  return lines.some((s) => GENERATED_MARK.test(s));
}
export const hideOpts = (settings) => ({ untouched: settings?.untouched === "hide", tests: (settings?.tests ?? "hide") === "hide" });
export function indexGraph(g, hide = {}) {
  const ix = { placement: new Map(), node: new Map(), hunk: new Map(), core: new Map(), edgesByCore: new Map(), walkPos: new Map() };
  for (const n of g.nodes) ix.node.set(n.id, n);
  for (const h of g.hunks) ix.hunk.set(h.id, h);
  g.cores.forEach((c, ci) => {
    ix.core.set(c.id, { core: c, ci });
    for (const b of BANDS) for (const pl of c.bands[b]) ix.placement.set(pl.id, { pl, core: c, ci });
  });
  const quiet = new Map(); // node id → test or generated
  const shown = (pid) => {
    const pl = ix.placement.get(pid)?.pl;
    if (!pl) return true;
    if (hide.untouched && (pl.band === "upUnchanged" || pl.band === "downUnchanged")) return false;
    if (hide.tests) { if (!quiet.has(pl.node)) quiet.set(pl.node, isTestOrGenerated(ix.node.get(pl.node), ix)); if (quiet.get(pl.node)) return false; }
    return true;
  };
  for (const e of g.edges) if (shown(e.from) && shown(e.to)) (ix.edgesByCore.get(e.core) ?? ix.edgesByCore.set(e.core, []).get(e.core)).push(e);
  ix.walk = [...g.walk.filter(shown), ...(g.lowSignal.length ? [LOW] : []), DONE];
  ix.hide = hide;
  ix.shown = shown;
  ix.walk.forEach((id, i) => ix.walkPos.set(id, i));
  return ix;
}

export function createApp({ graph, session }) {
  const listeners = new Set();
  session.state.notes ??= [];
  const app = {
    graph,
    index: indexGraph(graph, hideOpts({ ...DEFAULT_SETTINGS, ...session.settings })),
    state: session.state,
    settings: { ...DEFAULT_SETTINGS, ...session.settings },
    caps: session.caps,
    llm: session.llm,
    servers: session.servers ?? [],
    me: session.me ?? null, // your GitHub login and avatar, for your drafts // a language server per language in the review: where each stands (servers.ts)
    focus: null,
    level: 0,
    page: { exp: {}, open: new Set(), sel: null, composing: null }, // transient code-page state; open = unfolded blocks

    on(fn) { listeners.add(fn); return () => listeners.delete(fn); },
    emit(reason) { for (const fn of listeners) fn(reason); },

    // ---- lookups
    get(pid) { return app.index.placement.get(pid); },
    canonical(pid) { const p = app.get(pid)?.pl; return p?.repeatOf ?? pid; },
    nodeOf(pid) { const p = app.get(pid)?.pl; return p && app.index.node.get(p.node); },
    hunksOf(pid) {
      if (pid === LOW) return graph.lowSignal.map((id) => app.index.hunk.get(id));
      const n = app.nodeOf(pid);
      return n?.kind === "change" ? n.hunkIds.map((id) => app.index.hunk.get(id)).filter(Boolean) : [];
    },
    edgesOf(coreId) { return app.index.edgesByCore.get(coreId) ?? []; },
    neighbours(pid) {
      const c = app.get(pid)?.core;
      if (!c) return { up: [], down: [] };
      const es = app.edgesOf(c.id);
      return { up: es.filter((e) => e.to === pid), down: es.filter((e) => e.from === pid) };
    },
    stat(pid) {
      let a = 0, d = 0;
      for (const h of app.hunksOf(pid)) for (const l of h.lines) l.t === "+" ? a++ : l.t === "-" ? d++ : 0;
      return { a, d };
    },
    /** A core's placements in one band, without any the untouched switch hides. */
    band(c, b) { return c.bands[b].filter((pl) => app.index.shown(pl.id)); },
    /** Whether a core has anything left to show once the switches have hidden what they hide. */
    coreShown(c) { return BANDS.some((b) => app.band(c, b).length); },
    corePlacements(c) { return BANDS.flatMap((b) => app.band(c, b)); },

    // ---- review marks (keyed by content, so they survive re-pushes and tree regeneration)
    markKeys(pid) {
      pid = app.canonical(pid);
      if (pid === LOW) return app.hunksOf(LOW).map((h) => h.hash);
      const n = app.nodeOf(pid);
      if (!n) return [];
      return n.kind === "context" ? [`ref:${n.location.path}:${n.location.line}`] : app.hunksOf(pid).map((h) => h.hash);
    },
    isReviewed(pid) { const k = app.markKeys(pid); return k.length > 0 && k.every((x) => app.state.marks[x] === "reviewed"); },
    isFlagged(pid) { return app.markKeys(pid).some((x) => app.state.marks[x] === "flagged"); },
    mark(pid, mark) {
      const keys = app.markKeys(pid);
      const was = keys.map((k) => app.state.marks[k]);
      for (const k of keys) mark ? (app.state.marks[k] = mark) : delete app.state.marks[k];
      api("/api/mark", { keys, mark }).catch((e) => app.unmark(keys, was, e)); // shown at once; put back if not saved
      app.emit("marks");
    },
    // ---- scroll positions: each node's code remembers where you'd scrolled to, by zoom level (a card and a page lay
    // out differently), so coming back to a node picks up where you left it instead of at the top.
    scrolls: new Map(),
    /** Restores el's scroll for this node and level, and keeps track of it from now on. */
    keepScroll(el, pid = app.focus, level = app.level) {
      if (!el) return;
      const key = `${level}:${app.canonical(pid)}`;
      el._scrollKey = key;
      el.scrollTop = app.scrolls.get(key) ?? 0;
      if (el._scrollKept) return;
      el._scrollKept = true;
      el.addEventListener("scroll", () => { if (el._scrollKey) app.scrolls.set(el._scrollKey, el.scrollTop); }, { passive: true });
    },

    // ---- dependency levels: a page's distance from its core change along the core's edges. 0 is the core change,
    // 1, 2… what it affects, −1, −2… what it relies on; a page linked to nothing takes its band's level.
    coreLevels(core) {
      const cache = (app.index.levels ??= new Map());
      let lvl = cache.get(core.id);
      if (lvl) return lvl;
      const es = app.edgesOf(core.id), pls = app.corePlacements(core);
      lvl = new Map();
      for (const pl of pls) if (pl.band === "core") lvl.set(pl.id, 0);
      for (let changed = true, n = 0; changed && n < pls.length; n++) {
        changed = false;
        for (const e of es) {
          const a = app.get(e.from)?.pl, b = app.get(e.to)?.pl;
          if (!a || !b) continue;
          if (lvl.has(e.from) && !lvl.has(e.to) && !b.band.startsWith("up")) { lvl.set(e.to, lvl.get(e.from) + 1); changed = true; }
          if (lvl.has(e.to) && !lvl.has(e.from) && a.band.startsWith("up")) { lvl.set(e.from, lvl.get(e.to) - 1); changed = true; }
        }
      }
      const bandLvl = { upUnchanged: -2, upChanged: -1, core: 0, downChanged: 1, downUnchanged: 2 };
      for (const pl of pls) if (!lvl.has(pl.id)) lvl.set(pl.id, bandLvl[pl.band]);
      cache.set(core.id, lvl);
      return lvl;
    },
    pageLevel(pid) { const loc = app.get(pid); return loc ? app.coreLevels(loc.core).get(loc.pl.id) : undefined; },
    /** A file's level: that of its page closest to a core change (ties: the one it affects, not relies on); within
     *  `core` when given (its repeats included, so a file shown in that core counts there). */
    fileLevel(path, core) {
      const at = (p) => { const n = app.nodeOf(p); return n && (n.kind === "change" ? n.file : n.location.path); };
      const pids = core ? app.corePlacements(core).map((pl) => pl.id).filter((p) => at(p) === path && app.index.walkPos.has(app.canonical(p))) : app.filePages(path);
      const ls = pids.map((p) => (core ? app.coreLevels(core).get(p) : app.pageLevel(p))).filter((l) => l != null);
      return ls.length ? ls.sort((a, b) => Math.abs(a) - Math.abs(b) || b - a)[0] : undefined;
    },

    // ---- whole files: every page of the walk that shows code in a file
    filePages(path) {
      const at = (p) => { const n = app.nodeOf(p); return n && (n.kind === "change" ? n.file : n.location.path); };
      return app.index.walk.filter((p) => app.get(p) && !app.get(p).pl.repeatOf && at(p) === path);
    },
    isFileRead(path) { const ps = app.filePages(path); return ps.length > 0 && ps.every((p) => app.isReviewed(p)); },
    /** Marks a whole file viewed, or clears it when it already is: one save, one re-render. */
    markFile(path, on = !app.isFileRead(path)) {
      const keys = [...new Set(app.filePages(path).flatMap((p) => app.markKeys(p)))];
      const was = keys.map((k) => app.state.marks[k]);
      for (const k of keys) on ? (app.state.marks[k] = "reviewed") : delete app.state.marks[k];
      api("/api/mark", { keys, mark: on ? "reviewed" : null }).catch((e) => app.unmark(keys, was, e));
      app.emit("marks");
    },
    /** A mark the server didn't save: back to what it was, and say so. */
    unmark(keys, was, e) {
      keys.forEach((k, i) => (was[i] ? (app.state.marks[k] = was[i]) : delete app.state.marks[k]));
      app.emit("marks");
      app.fail?.(e);
    },
    progress() {
      const pages = app.index.walk.filter((p) => p !== DONE);
      const left = pages.filter((p) => !app.isReviewed(p));
      const secs = left.reduce((s, p) => { const { a, d } = app.stat(p); return s + 12 + (a + d) * 1.1; }, 0);
      return { done: pages.length - left.length, total: pages.length, mins: Math.round(secs / 60) };
    },

    // ---- private notes: on a line, a file (no line) or the PR (no path). Never posted to GitHub.
    async addNote(n) {
      const note = await api("/api/notes", n);
      app.state.notes.push(note);
      app.emit("comments"); // shown where comments are, so views re-render the same way
      return note;
    },
    async deleteNote(id) {
      const n = app.state.notes.find((x) => x.id === id);
      await api(`/api/notes/${id}`, null, "DELETE"); // gone once the server says so
      app.state.notes = app.state.notes.filter((x) => x.id !== id);
      app.emit("comments");
      if (n) { const { id: _, createdAt: __, ...fields } = n; app.offerUndo("Note deleted", () => app.addNote(fields)); }
    },
    /** Something just deleted: a toast offers to put it back, until the next one. */
    offerUndo(what, restore) { app._undo = restore; app.toastUndo?.(what); },
    /** The page that shows a file's line (or just the file), for jumping to a note. */
    pidAt(path, line) {
      let first = null;
      for (const pid of app.index.walk) {
        const n = app.nodeOf(pid);
        if (!n || (n.kind === "change" ? n.file : n.location.path) !== path) continue;
        first ??= pid;
        if (!line) break;
        const hit = n.kind === "context"
          ? line >= n.snippet.start && line < n.snippet.start + n.snippet.lines.length
          : app.hunksOf(pid).some((h) => (line >= h.newStart && line < h.newStart + h.lines.length) || (line >= h.oldStart && line < h.oldStart + h.lines.length));
        if (hit) return pid;
      }
      return first;
    },

    // ---- navigation (always along graph.walk, so every view agrees on "next")
    setFocus(pid, { level } = {}) {
      if (!pid) return;
      pid = app.canonical(pid);
      const changed = pid !== app.focus;
      app.focus = pid;
      const fileNote = app.page.composing?.file ? app.page.composing : null; // a note on the whole file outlives moving within it
      if (!fileNote && app.page.composing) app.keepDraft?.(app.page.composing); // moving away keeps what you wrote, as esc does
      // the inspector's window is on top of everything and closes itself: a focus change underneath (a scroll's read
      // focus, a click) keeps it, or it would stay drawn with nothing behind it, swallowing every key
      app.page = { exp: app.page.exp, open: app.page.open, kind: app.page.kind, sel: null, selKeys: null, anchor: null, composing: fileNote, peek: app.page.peek };
      if (level !== undefined && level !== app.level) { app.level = level; app.emit("level"); }
      if (changed) {
        app.emit("focus");
        app.savePosition();
      }
    },
    setLevel(l) {
      l = Math.max(0, Math.min(2, l));
      if (l === app.level) return;
      app.level = l;
      if (app.page.composing) app.keepDraft?.(app.page.composing);
      app.page.composing = null;
      app.emit("level");
      app.savePosition();
    },
    /** Remembers the page and zoom level, debounced, so a return lands where you were. */
    savePosition() {
      clearTimeout(app._pos);
      app._pos = setTimeout(() => api("/api/position", { nodeId: app.nodeOf(app.focus)?.id ?? app.focus, level: app.level }), 500);
    },
    step(d) {
      const i = app.index.walkPos.get(app.focus) ?? 0;
      app.setFocus(app.index.walk[Math.max(0, Math.min(app.index.walk.length - 1, i + d))]);
    },
    stepCore(d) {
      const cur = app.get(app.focus)?.ci ?? graph.cores.length; // the Low-signal and End pages come after every core
      let target = cur + d, first;
      while (target >= 0 && target < graph.cores.length && !(first = app.index.walk.find((p) => app.get(p)?.ci === target))) target += d; // skip cores the switches emptied
      if (target < 0) return;
      if (target >= graph.cores.length) { // past the last core: Low-signal, then End
        const after = app.index.walk.filter((p) => !app.get(p));
        return app.setFocus(after[after.indexOf(app.focus) + 1] ?? after.at(-1) ?? DONE);
      }
      app.setFocus(first);
    },
    /**
     * Where to start a PR you haven't opened before: the core with the fewest up- and downstream pages
     * (its dependencies), then the fewest changed lines. Cores linked to nothing are only used if every
     * core is like that, so you start somewhere small but central. Returns that core's first unreviewed page.
     */
    entryPoint() {
      const cores = graph.cores.map((c, ci) => {
        const pages = app.index.walk.filter((p) => app.get(p)?.ci === ci && !app.isReviewed(p));
        const deps = BANDS.filter((b) => b !== "core").reduce((n, b) => n + c.bands[b].length, 0);
        const size = app.corePlacements(c).reduce((n, pl) => { const { a, d } = app.stat(pl.id); return n + a + d; }, 0);
        return { c, pages, deps, size };
      }).filter((x) => x.pages.length);
      const linked = cores.filter((x) => x.deps > 0);
      const pool = linked.length ? linked : cores;
      pool.sort((x, y) => x.deps - y.deps || x.size - y.size);
      const best = pool[0];
      // Start at changed code: the core change itself, else the first changed page, never the context around it.
      const changed = (p) => app.nodeOf(p)?.kind === "change";
      const pid = best && (best.pages.find((p) => app.get(p).pl.band === "core") ?? best.pages.find(changed) ?? best.pages[0]);
      return best && { pid, deps: best.deps };
    },
    /** `F`: the deep pass. Next flagged page after the focus, wrapping around. Returns false if nothing is flagged. */
    nextFlagged() {
      const w = app.index.walk, i = app.index.walkPos.get(app.focus) ?? -1;
      for (let k = 1; k <= w.length; k++) {
        const p = w[(i + k) % w.length];
        if (app.get(p) && app.isFlagged(p)) { app.setFocus(p); return true; }
      }
      return false;
    },
    nextUnreviewed() {
      const w = app.index.walk, i = app.index.walkPos.get(app.focus) ?? -1;
      for (let k = 1; k <= w.length; k++) {
        const p = w[(i + k) % w.length];
        if (p !== DONE && !app.isReviewed(p)) return app.setFocus(p);
      }
      app.setFocus(DONE);
    },

    // ---- diff layout: global (a setting), or switched for one file until the global one changes
    fileLayout: new Map(),
    layoutOf(path) { return app.fileLayout.get(path) ?? app.settings.diffLayout; },
    toggleLayout(path) {
      if (!path) return app.saveSettings({ diffLayout: app.settings.diffLayout === "split" ? "inline" : "split" });
      const next = app.layoutOf(path) === "split" ? "inline" : "split";
      if (next === app.settings.diffLayout) app.fileLayout.delete(path); else app.fileLayout.set(path, next);
      app.emit("settings");
    },

    // ---- settings
    saveSettings(patch) {
      if ("diffLayout" in patch) app.fileLayout.clear(); // the global layout applies to every file again
      Object.assign(app.settings, patch);
      api("/api/settings", patch);
      const h = hideOpts(app.settings);
      if (h.untouched !== app.index.hide.untouched || h.tests !== app.index.hide.tests) return app.reindex();
      app.emit("settings");
    },
    useKey(k) {
      const u = app.settings.hintUses;
      u[k] = (u[k] ?? 0) + 1;
      if (u[k] === 5) app.saveSettings({ hintUses: u });
    },

    /** Rebuild the index for the switches, keeping the focus (or, if it was hidden, the page it was attached to). */
    reindex() {
      const was = app.focus, loc = app.get(was);
      app.index = indexGraph(graph, hideOpts(app.settings));
      if (!app.index.walkPos.has(was)) {
        const e = graph.edges.find((x) => x.from === was && app.index.walkPos.has(x.to)) ?? graph.edges.find((x) => x.to === was && app.index.walkPos.has(x.from));
        const to = e && (e.from === was ? e.to : e.from); // a hidden page: go to what it fed, or what it hung off
        app.focus = (to && app.index.walkPos.has(to) ? to : null) ?? (loc && app.band(loc.core, "core")[0]?.id) ?? app.entryPoint()?.pid ?? app.index.walk[0];
      }
      app.emit("graph"); // one event: every view rebuilds on it, and a "settings" too would rebuild them twice
    },
    replaceGraph(g) {
      const keepNode = app.nodeOf(app.focus)?.id;
      app.graph = graph = g;
      app.index = indexGraph(g, hideOpts(app.settings));
      const pid = keepNode && [...app.index.placement.values()].find((x) => x.pl.node === keepNode && !x.pl.repeatOf)?.pl.id;
      app.focus = pid ?? app.index.walk[0];
      app.emit("graph");
    },
  };
  return app;
}
