import { describe, expect, test } from "bun:test";

// core.js reads the page's address when it loads
(globalThis as { location?: unknown }).location ??= { pathname: "/" };
// @ts-expect-error: plain JS module
const { indexGraph } = await import("../public/app/core.js");

type Line = { t: string; o: number | null; n: number | null; s: string };
const add = (n: number, s: string): Line => ({ t: "+", o: null, n, s });
const ctx = (n: number, s: string): Line => ({ t: " ", o: n, n, s });

/** One core whose page per hunk is a node of its own: a file split into units, as extraction makes them. */
function graph(hunks: Array<{ id: string; file: string; lines: Line[] }>) {
  const nodes = hunks.map((h) => ({ id: `chg:${h.file}#${h.id}`, kind: "change", file: h.file, hunkIds: [h.id] }));
  const core = nodes.map((n, i) => ({ id: `p${i + 1}`, node: n.id, band: "core", title: n.id, why: "" }));
  return { hunks, nodes, cores: [{ id: "c1", bands: { upUnchanged: [], upChanged: [], core, downChanged: [], downUnchanged: [] } }], edges: [], walk: core.map((p) => p.id), lowSignal: [] };
}
const walked = (g: ReturnType<typeof graph>) => indexGraph(g, { generated: true }).walk.filter((p: string) => !p.startsWith("@"));

describe("hiding generated files", () => {
  test("a marker phrase in a file's code doesn't hide the hunk it's in", () => {
    const g = graph([
      { id: "h1", file: "src/users.ts", lines: [ctx(1, "export interface User {"), add(2, "  createdAt: Date;")] },
      { id: "h2", file: "src/users.ts", lines: [ctx(40, "export function makeUser() {"), add(41, "  // The id is auto-generated here, so callers never pass one."), add(42, "  const id = crypto.randomUUID();")] },
      { id: "h3", file: "src/users.ts", lines: [ctx(80, "  // DO NOT EDIT the order of these checks"), add(81, "  return ok;")] },
    ]);
    expect(walked(g)).toEqual(["p1", "p2", "p3"]);
  });

  test("a generator's header hides the whole file, every part of it", () => {
    const g = graph([
      { id: "h1", file: "src/api/client.ts", lines: [ctx(1, "// Code generated by openapi-gen. DO NOT EDIT."), ctx(2, ""), add(3, "export type Id = string;")] },
      { id: "h2", file: "src/api/client.ts", lines: [ctx(300, "export function get() {"), add(301, "  return fetch(url);")] },
      { id: "h3", file: "src/app.ts", lines: [add(5, "import { get } from './api/client';")] },
    ]);
    expect(walked(g)).toEqual(["p3"]);
  });

  test("a marker that isn't a comment, or is past the header, isn't one", () => {
    const g = graph([
      { id: "h1", file: "src/a.ts", lines: [add(2, 'const label = "auto-generated";')] },
      { id: "h2", file: "src/b.ts", lines: [ctx(11, "// @generated"), add(12, "x();")] },
    ]);
    expect(walked(g)).toEqual(["p1", "p2"]);
  });

  test("by path, as before; and shown when the switch is off", () => {
    const g = graph([{ id: "h1", file: "src/__generated__/schema.ts", lines: [add(1, "export {};")] }, { id: "h2", file: "src/x.ts", lines: [add(1, "y();")] }]);
    expect(walked(g)).toEqual(["p2"]);
    expect(indexGraph(g, { generated: false }).walk.filter((p: string) => !p.startsWith("@"))).toEqual(["p1", "p2"]);
  });
});
